# Ler um número e mostrar o seu dobro, triplo e raiz quadrada

numero = float(input('Digite um número qualquer: '))
print('-' * 40)
print('O número digitado foi {}.'.format(numero))
print('O dobro dele é {}.'.format(numero * 2))
print('Já o seu triplo é {}.'.format(numero * 3))
print('E a sua raíz quadrada é {}'.format(numero ** 0.5))